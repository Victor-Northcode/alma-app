"""Воркер gunicorn — наследник uvicorn'овского ради одного числа.

**`UvicornWorker` не задаёт `timeout_graceful_shutdown`, и без него остановка
процесса ведёт себя не так, как о ней написано везде остальное.**

`uvicorn.Server.shutdown` без этого числа ждёт закрытия открытых соединений
**без предела**, и только потом запускает остановку приложения. У нас есть
соединение, которое само не закроется: `/v1/chat/stream` держится всю
генерацию, а её бюджет назван тремя минутами (`gunicorn.conf.py`, `timeout`).
Порядок при выкладке с живым читателем получался такой:

    SIGTERM → uvicorn ждёт SSE → SIGKILL на 120-й секунде

то есть `lifespan` не запускался вовсе, а вместе с ним не запускался
`app._drain_stream_turns` со своими ста секундами ожидания оплаченных ходов.
Ожидание, написанное ради выкладки, при выкладке и не срабатывало ни разу —
самый тихий вид неработающей защиты: код есть, тесты на него зелёные, а на
живой машине до него не доходит управление.

Пятнадцать секунд — это «дай соединениям закрыться по-человечески», а не
«дождись конца работы». Работу ждёт `_drain_stream_turns`, и ждёт он её уже
после того, как соединения отпущены: 15 + 100 = 115 < 120 `graceful_timeout`.

Отдельным модулем, а не классом в `gunicorn.conf.py`, по прозаичной причине:
`worker_class` gunicorn импортирует по точечному пути, а `gunicorn.conf` как
модуль не существует — файл конфигурации называется `gunicorn.conf.py`, но
модулем не является. Путь `alma.api.worker` импортируется откуда угодно, в том
числе из прод-образа, где `alma` лежит рядом с конфигом.
"""

from __future__ import annotations

from uvicorn.workers import UvicornWorker

#: Сколько ждать закрытия соединений до того, как начнётся остановка приложения.
#: Меняется вместе с `app.STREAM_TURN_GRACE_SECONDS` и `graceful_timeout` —
#: сумма первых двух обязана оставаться меньше третьего. Стережёт
#: `tests/test_ten_thousand.py`.
CONNECTION_GRACE_SECONDS = 15


class AlmaUvicornWorker(UvicornWorker):
    CONFIG_KWARGS = {"timeout_graceful_shutdown": CONNECTION_GRACE_SECONDS}
