"""Один HTTP-клиент на процесс — для магазинов и касс.

**Что было.** Каждый вызов к Google Play, Paddle и Dodo открывал свой
`httpx.AsyncClient` через `async with` и закрывал его на выходе. Это значит: на
каждую проверку покупки — новое TCP-соединение, новое TLS-рукопожатие и новый
DNS-поиск, а после ответа всё это выбрасывается. Проверка одной покупки в
Google Play — это **два** таких вызова подряд (сперва токен сервисного
аккаунта, потом сам запрос), то есть два рукопожатия там, где хватило бы нуля.

Цена не теоретическая. TLS-рукопожатие до `oauth2.googleapis.com` из Европы —
это два круга по сети, 60–120 мс на круг; на десяти тысячах пользователей и
паре тысяч проверок покупок в сутки это часы процессорного ожидания, потраченные
на то, чтобы каждый раз заново здороваться с теми же тремя хостами. Живой
клиент держит соединения открытыми (`keep-alive`) и второй запрос к тому же
хосту начинает сразу с данных.

**Почему один на процесс, а не один на класс клиента.** Пул считается по хостам
внутри клиента, поэтому три вендора в одном клиенте не мешают друг другу, а
три клиента — это три пула, три набора таймаутов и три места, где однажды
разойдутся цифры. Закрывается он в `lifespan` (`api/app.py`), потому что
`httpx` без закрытия оставляет открытые сокеты, а воркер, уходящий по SIGTERM,
обязан отпустить их до того, как его снимут.

**Таймауты названы поимённо, а не одним числом.** Прежнее `timeout=10.0`
означало десять секунд на *каждую* фазу, включая установление соединения; на
подвисшем DNS это давало сорок секунд ожидания там, где человек стоит перед
экраном «проверяем покупку». Здесь фаза подключения короткая (сеть либо есть,
либо её нет), а чтение остаётся прежним — вендор имеет право думать.
"""

from __future__ import annotations

import logging

import httpx

log = logging.getLogger("alma.billing.http")

#: Сколько ждать установления соединения. Две секунды — это «сеть до вендора
#: есть»; всё, что дольше, — это не медленный вендор, а недоступный.
CONNECT_TIMEOUT = 2.0

#: Сколько ждать ответа. Десять секунд, ровно как было: столько магазины и
#: кассы иногда думают над проверкой покупки, и укорачивать это заодно с
#: переездом на общий клиент значило бы тихо сделать отказов больше.
READ_TIMEOUT = 10.0

#: Сколько соединений держать открытыми между вызовами. Хостов у нас три
#: (`oauth2.googleapis.com`, `androidpublisher.googleapis.com` и касса), по
#: несколько соединений на каждый: одновременных проверок покупки на выкладке
#: акции бывает больше одной, а очередь за соединением — это те же
#: рукопожатия, только с ожиданием.
MAX_KEEPALIVE = 20

#: Потолок одновременных соединений. Выше пула вебхуков и ниже любого числа, на
#: котором вендор начинает отвечать 429 за частоту.
MAX_CONNECTIONS = 50

#: Сколько держать простаивающее соединение. Полминуты: балансировщики Google и
#: касс рвут простой раньше минуты, а соединение, порванное с той стороны,
#: обнаруживается как ошибка на следующем запросе — то есть как отказ проверить
#: чью-то покупку.
KEEPALIVE_EXPIRY = 30.0

_client: httpx.AsyncClient | None = None


def client() -> httpx.AsyncClient:
    """Общий клиент этого процесса, созданный при первом обращении.

    Лениво, а не при импорте: `httpx.AsyncClient` привязывает свой пул к
    событийному циклу, в котором его впервые использовали, а импорт случается
    до того, как цикл вообще есть — в том числе в командах `tools/`, которым
    HTTP не нужен вовсе.
    """
    global _client
    if _client is None or _client.is_closed:
        _client = httpx.AsyncClient(
            timeout=httpx.Timeout(READ_TIMEOUT, connect=CONNECT_TIMEOUT),
            limits=httpx.Limits(
                max_keepalive_connections=MAX_KEEPALIVE,
                max_connections=MAX_CONNECTIONS,
                keepalive_expiry=KEEPALIVE_EXPIRY,
            ),
        )
    return _client


async def aclose() -> None:
    """Закрыть клиент и его соединения. Зовётся из `lifespan` и из тестов."""
    global _client
    if _client is not None and not _client.is_closed:
        try:
            await _client.aclose()
        except Exception as exc:  # noqa: BLE001 — закрытие не роняет остановку
            log.info("closing the billing http client: %s", exc)
    _client = None
