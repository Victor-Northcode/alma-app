"""Солнечный знак по одной дате рождения — и честное «не знаю» на границе.

**Зачем отдельно от натального расчёта.** Полный расчёт требует места и
времени рождения и стоит эфемеридного прохода по десятку тел; для списка людей
(«Мои пары», строка партнёра) это десяток расчётов ради одного глифа в кружке.
Солнцу же не нужны ни дома, ни асцендент: его знак определяется датой почти
всегда однозначно.

**Почти** — и вот это «почти» здесь главное. В день, когда Солнце переходит из
знака в знак, ответ зависит от часа рождения: родившийся утром 20 марта — Рыбы,
родившийся вечером — Овен. Времени рождения у партнёра может не быть вовсе, а
угадать его молча значило бы назвать человека чужим знаком — ровно тот сорт
уверенной неправды, которого продукт не допускает нигде.

Поэтому функция проверяет знак **на обоих концах суток UTC** и отвечает `None`,
когда они разошлись. Календарных таблиц «21 марта — Овен» здесь нет намеренно:
даты границ плывут от года к году, и таблица, верная сегодня, врёт на дедушке.
"""

from __future__ import annotations

from datetime import date, datetime, timezone

from . import ephemeris, zodiac
from .timeutil import _julian_day


def sun_sign_of_date(day: date) -> str | None:
    """Знак Солнца в этот день или `None`, если день пограничный.

    Считается по календарным суткам UTC, а не по местным: часового пояса
    рождения у этой функции нет по построению, а сутки UTC — самый широкий
    honest-интервал, внутри которого лежит любой местный момент этого дня.
    Шире — значит осторожнее: пограничным объявится и день, который в
    конкретном поясе однозначен. Ошибиться в сторону молчания дешевле.
    """
    start = datetime(day.year, day.month, day.day, 0, 0, tzinfo=timezone.utc)
    end = datetime(day.year, day.month, day.day, 23, 59, tzinfo=timezone.utc)
    first = zodiac.sign_of(ephemeris.position("sun", _julian_day(start)).longitude)
    last = zodiac.sign_of(ephemeris.position("sun", _julian_day(end)).longitude)
    return first if first == last else None
