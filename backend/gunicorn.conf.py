"""Как запускается прод. Один файл, потому что цифры здесь — это решения.

`uvicorn alma.api.app:app` — то, чем прод жил до сих пор, — это **один процесс
на одном ядре без присмотра**. Он не переживает собственного падения, не
использует второе ядро и не умеет выкатываться без обрыва. Gunicorn решает все
три: он менеджер процессов, который держит N воркеров, перезапускает упавшего и
умеет заменять их по одному.

Класс воркера — `uvicorn.workers.UvicornWorker`: приложение асинхронное, и
синхронный воркер выполнял бы одновременно ровно один запрос на процесс,
превращая `/v1/chat/stream` в очередь.
"""

from __future__ import annotations

import multiprocessing
import os


def _int(name: str, default: int) -> int:
    """Целое из окружения, молча падающее обратно на умолчание.

    Молча — потому что альтернатива хуже: процесс, отказавшийся стартовать
    из-за опечатки в необязательной ручке, — это выкатка, которая не поднялась
    из-за настройки, которую никто не собирался менять.
    """
    try:
        return int(os.getenv(name, "").strip() or default)
    except ValueError:
        return default


bind = os.getenv("ALMA_BIND", "0.0.0.0:8000")
worker_class = "uvicorn.workers.UvicornWorker"

#: **Число воркеров: по ядрам, но не по классической формуле.**
#:
#: `2 × ядра + 1` — правило для синхронных воркеров, где процесс простаивает
#: на каждом обращении к сети. Здесь наполовину не так: обращения к модели —
#: действительно ожидание, но расчёты — нет. Измерено на этой машине:
#: `chart_for` — 33 мс, трёхдневный `transits.scan` — 112 мс, а годовой скан
#: (`daily/service.SCAN_DAYS`) — 1.35 с. Это чистое процессорное время, и на
#: нём воркеров больше, чем ядер, не ускоряют, а разменивают ответы друг друга
#: на переключение контекста.
#:
#: Отсюда `ядра × 2`, а не `× 2 + 1`, и потолок в 8. Потолок — про память, а
#: не про процессор: каждый воркер — отдельный интерпретатор, который держит
#: своё ядро эфемерид и свои пулы; на машине с 16 ядрами и 4 ГБ памяти
#: тридцать три воркера — это не быстрее, это OOM-killer.
#:
#: `WEB_CONCURRENCY` — имя, которое читают все платформы (Heroku, Render,
#: Fly), поэтому оно здесь, а не наше собственное.
workers = _int("WEB_CONCURRENCY", min(8, max(2, multiprocessing.cpu_count() * 2)))

#: **120 секунд на то, чтобы доработать, и это самая дорогая цифра в файле.**
#:
#: При выкатке и при перезапуске воркер получает SIGTERM и должен закончить то,
#: что делает. По умолчанию у gunicorn на это 30 секунд, после чего SIGKILL.
#: Тридцати секунд не хватает: генерация главы — это вызов модели, которая
#: рассуждает перед тем, как писать, и `ai/provider.py` описывает живой случай,
#: где читатель ждал ответа **три минуты**. Воркер, убитый на второй минуте, —
#: это глава, за которую человек заплатил и которой не получил, и деньги за
#: вызов, который всё равно выставлен нам в счёт.
#:
#: Почему тогда не 180, как `timeout`? Потому что это время, на которое встаёт
#: **выкатка**: чем оно больше, тем дольше старый и новый код живут рядом. Две
#: минуты покрывают подавляющее большинство генераций и не превращают деплой в
#: ожидание. Три минуты — крайний случай, и он проигрывает.
graceful_timeout = _int("ALMA_GRACEFUL_TIMEOUT", 120)

#: **180 секунд, и это не таймаут запроса.**
#:
#: Для асинхронных воркеров это таймаут *живости*: арбитр убивает воркера, не
#: подавшего признаков жизни. `UvicornWorker` отмечается по таймеру своего цикла
#: событий, поэтому долгий запрос сам по себе сюда не попадает — попадает
#: заблокированный цикл, то есть настоящее зависание. Значение выбрано выше
#: самой долгой наблюдавшейся генерации (три минуты) с запасом: срабатывание
#: этого таймаута должно означать «процесс завис», а не «модель думает».
timeout = _int("ALMA_WORKER_TIMEOUT", 180)

#: Ожидание между запросами на живом соединении. Пять секунд по умолчанию — это
#: про голый gunicorn перед nginx; здесь перед нами обратный прокси, который
#: держит соединения открытыми, и разрыв keep-alive на каждом вздохе — это
#: лишнее рукопожатие TLS на ровном месте. 65 > 60 секунд, которые по умолчанию
#: держит nginx, — чтобы соединение закрывал прокси, а не мы под ним.
keepalive = _int("ALMA_KEEPALIVE", 65)

#: Перезапуск воркера после N запросов, с разбросом. Не «на всякий случай»:
#: любая утечка памяти в процессе, живущем неделями, однажды становится
#: OOM-killer в самый нагруженный час. Периодическая замена превращает
#: неизвестную утечку в неизвестную и безвредную. Разброс — чтобы восемь
#: воркеров не переродились на одном и том же запросе одновременно.
max_requests = _int("ALMA_MAX_REQUESTS", 2000)
max_requests_jitter = _int("ALMA_MAX_REQUESTS_JITTER", 200)

#: Куда писать логи: в поток, а не в файл. В контейнере файл журнала — это
#: место, откуда никто никогда не прочитает; `docker compose logs` и
#: `journalctl` читают потоки.
accesslog = os.getenv("ALMA_ACCESS_LOG", "-")
errorlog = "-"
loglevel = os.getenv("ALMA_LOG_LEVEL", "info")

#: Формат доступа с временем ответа в конце (`%(L)s` — секунды). Без него
#: вопрос «стало медленнее?» отвечается только гаданием.
#: **IP берётся из `X-Real-IP`**, а не из адреса сокета: за прокси сокет — это
#: всегда прокси, и журнал доступа, где все запросы пришли с одного адреса,
#: бесполезен ровно тогда, когда нужен. Тот же заголовок читает
#: `api/deps.request_source` для потолков по источнику — прокси обязан его
#: перезаписывать, см. `deploy/nginx.conf` и `deploy/Caddyfile`.
access_log_format = '%({x-real-ip}i)s "%(r)s" %(s)s %(b)s %(L)s "%(a)s"'

#: Предзагрузка выключена намеренно. `preload_app = True` экономит память, но
#: форкает воркеров из процесса, который уже открыл соединения и файлы; ядро
#: эфемерид и пулы SQLAlchemy этого не любят, а выигрыш — десятки мегабайт.
preload_app = False

#: Uvicorn доверяет заголовкам прокси только от перечисленных адресов. В compose
#: прокси — соседний контейнер со случайным адресом внутренней сети, а наружу
#: порт приложения не опубликован вовсе, поэтому `*` здесь означает «доверять
#: единственному, кто до нас дотягивается». Если порт приложения когда-нибудь
#: будет опубликован, это значение обязано стать адресом прокси — иначе клиент
#: назначит себе любой адрес сам.
forwarded_allow_ips = os.getenv("FORWARDED_ALLOW_IPS", "*")
