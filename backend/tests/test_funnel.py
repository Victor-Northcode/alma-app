def _run(db, work):
    async def go():
        async with db.session_scope() as session:
            return await work(session)

    return run_async(go)


def _person(session) -> User:
    user = User(id=new_id(), provider="guest", locale="en")
    session.add(user)
    return user


async def _walk(session, user: User, *stages: str, surface: str = "p1") -> None:
    """Take one person as far down the funnel as the caller says.

    Событию лестницы поверхность подставляется, всем прочим — нет: `record`
    первое без неё не запишет, а второму выбросил бы ярлык как незнакомый.
    """
    for stage in stages:
        ladder = funnel.BY_NAME[stage].monetization
        await funnel.record(
            session,
            user_id=user.id,
            stage=stage,
            properties={"surface": surface} if ladder else None,
        )


def _steps(steps) -> dict[str, funnel.Step]:
    return {step.stage: step for step in steps}


def test_of_the_people_who_reached_a_how_many_reached_b(db):
    """Four in at the top, one out at the bottom, and every rate in between.

    The set is small enough that the answer can be read off by hand, which is
    the only way to know a funnel query is right: three people start the quiz,
    two finish it, one opens a checkout.
    """
    async def seed(session):
        everyone = [_person(session) for _ in range(4)]
        await session.flush()
        a, b, c, d = everyone
        await _walk(session, a, "landing_view", "quiz_start", "quiz_complete",
                    "portrait_view", "offer_view", "checkout_opened")
        await _walk(session, b, "landing_view", "quiz_start", "quiz_complete")
        await _walk(session, c, "landing_view", "quiz_start")
        await _walk(session, d, "landing_view")
        return await funnel.funnel(session)

    steps = _steps(_run(db, seed))

    assert steps["landing_view"].reached == 4
    assert steps["landing_view"].rate is None       # nothing above it to divide by
    assert steps["quiz_start"].reached == 3
    assert steps["quiz_start"].rate == 0.75
    assert steps["quiz_complete"].reached == 2
    assert steps["portrait_view"].reached == 1
    assert steps["checkout_opened"].reached == 1
    assert steps["purchase"].reached == 0
    assert steps["purchase"].rate == 0.0


