def test_forgetting_reaches_back_to_before_the_account_existed(db):
    """The rows from the journey are theirs, and they do not carry the account id.

    Somebody who walked the whole journey and then saved a birth has their
    landing view filed under a browser id. Erasing only the rows that name the
    account would leave those behind — still joined to each other, still joined
    to a string that is still in that person's browser — while the privacy page
    says the step labels went with everything else. Somebody else's rows, under
    an id this account never claimed, must not go with them.
    """
    async def seed(session):
        mine, theirs = _person(session), _person(session)
        await session.flush()

        await funnel.record(session, user_id=None, anon_id="my-browser", stage="landing_view")
        await funnel.record(session, user_id=None, anon_id="my-browser", stage="quiz_start")
        await funnel.claim(session, anon_id="my-browser", user_id=mine.id)
        await _walk(session, mine, "quiz_complete")

        await funnel.record(
            session, user_id=None, anon_id="their-browser", stage="landing_view"
        )
        await _walk(session, theirs, "landing_view")

        gone = await funnel.forget(session, mine.id)
        left = (await session.execute(select(Event))).scalars().all()
        claims = (await session.execute(select(AnonymousVisitor))).scalars().all()
        return gone, {(row.user_id, row.anon_id) for row in left}, len(claims), theirs.id

    gone, left, claims, other = _run(db, seed)
    # Two from before the account and one from after it.
    assert gone == 3
    # Both of somebody else's, under both kinds of identity, untouched.
    assert left == {(None, "their-browser"), (other, None)}
    assert claims == 0


def test_nothing_outlives_the_retention_the_privacy_page_states(db):
    """A promise about deletion is worth what the code behind it does.

    Every row past the cutoff, not only the anonymous ones: deleting the
    unattributed top of an old funnel while leaving the purchases below it would
    leave a dataset that is not smaller but wrong, with every historical rate
    divided by a denominator that had been quietly shrunk.
    """
    async def seed(session):
        person = _person(session)
        await session.flush()
        await funnel.record(session, user_id=None, anon_id="old-browser", stage="landing_view")
        await funnel.claim(session, anon_id="old-browser", user_id=person.id)
        await _walk(session, person, "quiz_start")
        await funnel.record(session, user_id=None, anon_id="new-browser", stage="landing_view")

        long_ago = utcnow() - timedelta(days=funnel.PURGE_AFTER_DAYS + 1)
        for row in (
            await session.execute(
                select(Event).where(
                    (Event.anon_id == "old-browser") | (Event.user_id == person.id)
                )
            )
        ).scalars():
            row.created_at = long_ago
        for row in (await session.execute(select(AnonymousVisitor))).scalars():
            row.claimed_at = long_ago
        await session.flush()

        gone = await funnel.purge(session)
        left = (await session.execute(select(Event))).scalars().all()
        claims = (await session.execute(select(AnonymousVisitor))).scalars().all()
        return gone, [row.anon_id for row in left], claims

    gone, left, claims = _run(db, seed)
    assert gone == 2
    assert left == ["new-browser"]
    # The join goes with the rows it joined. It is an identifier of somebody's
    # too, and one kept after everything it pointed at is gone is a record of a
    # browser and an account and nothing else.
    assert claims == []


def test_a_claim_still_being_used_survives_the_cutoff(db):
    """An old claim whose browser came back yesterday is not dead weight.

    Deleting it on its own age would split one person in two at exactly the
    moment they returned, which is the failure this table exists to prevent —
    arriving through housekeeping instead of through a missing header.
    """
    async def seed(session):
        person = _person(session)
        await session.flush()
        await funnel.record(session, user_id=None, anon_id="old-browser", stage="landing_view")
        await funnel.claim(session, anon_id="old-browser", user_id=person.id)
        for row in (await session.execute(select(AnonymousVisitor))).scalars():
            row.claimed_at = utcnow() - timedelta(days=funnel.PURGE_AFTER_DAYS + 1)
        await session.flush()

        await funnel.purge(session)
        return (await session.execute(select(AnonymousVisitor))).scalars().all()

    assert len(_run(db, seed)) == 1


