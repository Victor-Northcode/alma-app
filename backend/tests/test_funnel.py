"""The funnel — the one table in this schema that was never written to.

Every conversion figure the pricing work stands on is an assumption until
these rows exist, so what is tested here is not "does a POST return 200". It
is the six properties that decide whether the numbers can be believed:

* a name outside the closed set never becomes a row, because one typo is a
  cohort that silently vanishes from a query nobody re-checks;
* the browser cannot claim a purchase, because that number decides how much
  money is spent on advertising;
* somebody who has told us nothing is counted, because most of this funnel
  happens in front of the sign-in wall and a funnel that starts at sign-in
  measures the wrong product — **and counting them does not enrol them**, which
  is the rule this route used to break on every page load;
* the browser id and the account minted out of it are one person, because a
  funnel whose halves cannot be joined has traded one broken measurement for
  another and reads 0% on data that looks healthy;
* deletion and retention reach the rows recorded before the account existed,
  because those are the ones that do not carry its id;
* and the arithmetic — of the people who reached A, how many reached B — is
  right on a seeded set whose answer can be read off by hand.
"""

from __future__ import annotations

import asyncio
from datetime import timedelta

import pytest
from conftest import database_url, read_async, run_async
from sqlalchemy import select

from alma import funnel
from alma.db.models import AnonymousVisitor, Event, Purchase, User, new_id, utcnow
from tests.conftest import SOFIA


