def test_opening_the_app_and_closing_it_leaves_nothing_behind(api):
    """The web's rule, on the surface where almost every real user is.

    `GET /v1/auth/session` mints for a caller with no token, and that is correct
    — it is one of the acts. What was wrong is that both apps called it on
    launch, unconditionally, so an install that opened the app and closed it
    again left an account behind: 100% of installs, before anybody had typed
    anything, which is the same arithmetic that turned "how many accounts are
    there" into a count of downloads on the web.

    Two halves, and this is the first: **the route really does mint**, so the
    guard in each app is load-bearing rather than decorative. If this route ever
    stopped creating, the second half of this test would keep passing while
    guarding nothing, and nobody would know the apps had been carrying a check
    they no longer needed.
    """
    assert _users(api) == []
    minted = api.get("/v1/auth/session")
    assert minted.status_code == 200
    assert len(_users(api)) == 1
    assert minted.headers.get("X-Alma-Token")


def test_neither_app_calls_a_minting_route_before_it_has_a_token():
    """The second half: on both platforms, launch reads and does not create.

    Source is read rather than behaviour observed, and the reason is the shape
    of this repository rather than a preference — the Python suite is the only
    gate that runs on every change, and the thing being defended is a property
    of two codebases it cannot import. The alternative was to leave the rule
    unasserted on the two clients that account for every real install, which is
    how it came to be broken on both of them in the first place.

    What is checked is an *ordering*, not a spelling of the fix: inside the
    launch path, the check that a token already exists comes before the call
    that would mint one, and it returns. A rename fails this loudly, which is
    the correct outcome — somebody renaming the guard should have to say so.

    The four calls a launch makes are covered by that one ordering. `profiles`,
    `entitlements` and `hub` all take `CurrentUser` on the server too, so any of
    them would mint the row the session call is being kept away from; both apps
    put them after the early return, and a rearrangement that moved one above it
    would move it above the guard as well.
    """
    from pathlib import Path

    root = Path(__file__).resolve().parents[2] / "mobile"
    apps = {
        "iOS": (
            root / "ios" / "Alma" / "State" / "AlmaSessionModel.swift",
            "func start() async {",
            "guard client.hasAccount else {",
            "client.session()",
        ),
        "Android": (
            root / "android" / "app" / "src" / "main" / "kotlin" / "ai" / "pazl" / "alma"
            / "core" / "SessionHolder.kt",
            "fun start(",
            "!client.hasSession",
            "client.session()",
        ),
    }

    for platform, (source, launch, guard, mints) in apps.items():
        if not source.exists():
            pytest.skip(f"the {platform} app is not in this checkout")
        text = source.read_text(encoding="utf-8")

        for marker in (launch, guard, mints):
            assert marker in text, f"{platform}: {marker!r} is no longer in {source.name}"

        assert text.index(launch) < text.index(guard) < text.index(mints), (
            f"{platform}: the launch path reaches a minting call before it has "
            "checked whether this install already has a token"
        )
        # And the guard has to *stop*, not merely observe. A branch that logs
        # and falls through is the bug with a comment on it.
        assert "return" in text[text.index(guard) : text.index(mints)], (
            f"{platform}: the token check does not return before the minting call"
        )


def test_a_checkout_is_recorded_by_the_server_that_opened_it(api, auth_headers, monkeypatch):
    """`checkout_opened` used to exist only on the browser's word.

    Which means a buyer with Do Not Track or Global Privacy Control set produced
    a purchase with no checkout above it: they fell out of the nested count, and
    the one conversion rate that decides advertising spend was computed on a
    denominator that systematically excluded privacy-conscious buyers. Duplicate
    rows from the beacon are harmless — the funnel counts distinct accounts.
    """
    from alma.api.routers import billing as router
    from alma.billing.paddle import PaddleProvider
    from alma.billing.provider import SessionHandle, stamp

    class Opens(PaddleProvider):
        async def open_session(self, *, product, user_id, currency, country=None, email=None):
            return SessionHandle(
                provider="paddle", product=product, currency=currency,
                cents=899, display="$8.99", custom_data=stamp(user_id, product),
            )

    from alma import config as config_module

    monkeypatch.setenv("PADDLE_WEBHOOK_SECRET", "pdl_ntfset_test")
    monkeypatch.setenv("PADDLE_API_KEY", "pdl_test")
    config_module.settings.cache_clear()
    monkeypatch.setattr(router, "billing_adapter", lambda *_, **__: Opens())
    try:
        opened = api.post(
            "/v1/billing/checkout", json={"product": "door.natal"}, headers=auth_headers
        )
        assert opened.status_code == 200
    finally:
        config_module.settings.cache_clear()

    rows = _events(api)
    assert [(row.name, row.properties.get("product")) for row in rows] == [
        ("checkout_opened", "door.natal")
    ]


