def test_the_client_that_ships_is_the_client_that_is_accepted(api, auth_headers):
    """Every stage `src/lib/track.ts` can send, read out of the file itself.

    A beacon swallows its own failures, so a disagreement between the two ends
    of this wire is invisible in production — not a 500 in a log, just a rung of
    the funnel that reads zero for ever on data that looks perfectly healthy.
    Which is why this posts the names the client actually declares rather than
    the names anybody believes it declares.
    """
    import re

    union = re.search(r"export type Stage =\s*((?:\s*\|\s*\"[a-z_]+\")+)", _client_source())
    assert union, "src/lib/track.ts no longer declares a Stage union this can read"
    stages = re.findall(r'"([a-z_]+)"', union.group(1))
