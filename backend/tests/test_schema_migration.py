"""A database that already exists has to keep working.

`create_all` creates missing tables and never touches one that is already
there, so every column added to a model since the last deploy is a column the
live database does not have — and the failure is a 500 on the first `SELECT`,
which here means the paywall, the hub, `/v1/account` and the billing webhook
at once. The suite could not see it, because every test database is built from
nothing.

These tests build the *old* shape on purpose and then assert that a boot
brings it forward. That is the only way to test a migration: against a
database that predates it.
"""

from __future__ import annotations

import asyncio

import pytest
from conftest import database_url, postgres_url, run_async
from sqlalchemy import select, text

from alma.db.migrate import SchemaTooOld, reconcile
from alma.db.models import Entitlement, Purchase


def _ddl(statement: str) -> str:
    """The same yesterday-shaped table, spelled for the database in use.

    The DDL below is written by hand precisely because the models no longer
    know how to declare it, which means it also cannot borrow SQLAlchemy's
    dialect rendering. Two spellings differ and both are load-bearing:
    `AUTOINCREMENT` is SQLite's and Postgres has identity columns instead, and
    `DATETIME` is a SQLite affinity that Postgres has never heard of — a
    migration test that ran only against SQLite would prove the migration on
    the one database this product does not deploy.
    """
    if postgres_url() is None:
        return statement
    return statement.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    ).replace("DATETIME", "TIMESTAMP WITH TIME ZONE")


