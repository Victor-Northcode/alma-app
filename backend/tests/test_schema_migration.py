def test_a_boot_gives_the_old_funnel_both_halves_of_the_join(
    database_without_the_anonymous_funnel,
):
    """The column arrives by ALTER and the table by create_all, and both must.

    Without the column the beacon writes nothing at all, which is loud. Without
    the *table* the beacon keeps working and the account is still minted — only
    the claim silently fails, so the stages before an account and the stages
    after it never fold together and the first conversion rate reads zero on a
    database that looks perfectly healthy. That is the quieter of the two
    failures and the reason this asserts on both.
    """
    from alma.db.models import AnonymousVisitor, Event

    db = database_without_the_anonymous_funnel

    async def work():
        await db.create_all()
        async with db.session_factory()() as session:
            old = (await session.execute(select(Event))).scalars().one()
            # A write of the new shape has to land on the migrated table, not
            # merely be declarable against the model.
            session.add(Event(anon_id="a-browser-with-no-account", name="landing_view",
                              properties={}))
            session.add(AnonymousVisitor(anon_id="a-browser-with-no-account", user_id="u1"))
            await session.flush()
            rows = (await session.execute(select(Event))).scalars().all()
            claims = (await session.execute(select(AnonymousVisitor))).scalars().all()
            return old.anon_id, [r.anon_id for r in rows], [c.user_id for c in claims]

    before, after, claims = run_async(work)
    # The rows that predate the column read as "no browser id", which is the
    # truth about them: they were written by people who had already been given
    # an account for looking at a page.
    assert before is None
    assert sorted(a or "" for a in after) == ["", "a-browser-with-no-account"]
    assert claims == ["u1"]


