def test_the_old_shape_is_unqueryable_until_it_is_brought_forward(old_database):
    """The failure this exists to prevent, reproduced before it is fixed.

    `DatabaseError` rather than `OperationalError`: SQLite reports an unknown
    column as operational and Postgres reports it as programming, and the
    assertion that matters is the column name in the message, not which of
    SQLAlchemy's two wrappers carried it.
    """
    from sqlalchemy.exc import DatabaseError

    async def work():
        async with old_database.session_factory()() as session:
            await session.execute(select(Entitlement).limit(1))

    with pytest.raises(DatabaseError, match="subscription_id"):
        run_async(work)


def test_a_boot_brings_an_existing_database_forward(old_database):
    """`create_all` alone does not, which is the whole point."""
    async def work():
        await old_database.create_all()
        async with old_database.session_factory()() as session:
            held = (await session.execute(select(Entitlement))).scalars().all()
            paid = (await session.execute(select(Purchase))).scalars().all()
            return held, paid

    held, paid = run_async(work)
    assert [e.system for e in held] == ["natal"]
    assert held[0].subscription_id is None
    assert held[0].renews_at is None
    assert [p.transaction_id for p in paid] == ["txn_old"]


def test_a_row_written_before_scope_existed_is_backfilled_not_left_null(old_database):
    """`covers()` reads `scope` first now, so a NULL there is not "no opinion".

    It would fall through to the legacy shape by accident rather than by rule,
    and the next branch added above the fall-through would silently change
    what every pre-existing purchase means. The column carries a server
    default so the database fills it in, not just this process.
    """
    async def work():
        await old_database.create_all()
        async with old_database.session_factory()() as session:
            row = (await session.execute(select(Entitlement))).scalars().one()
            return row.scope, row.covers("natal"), row.covers("transits")

    scope, own, other = run_async(work)
    assert scope == "system"
    assert own is True and other is False


def test_running_it_twice_changes_nothing(old_database):
    """It runs on every boot, so the second boot has to be a no-op."""
    async def work():
        await old_database.create_all()
        return await reconcile()

    assert run_async(work) == []


def test_a_change_it_cannot_make_is_refused_rather_than_skipped():
    """A migration that silently declines half its work is the original bug.

    A NOT NULL column with no server default has nothing to put in the rows
    that already exist — SQLite refuses outright and Postgres has to be told —
    so it is a change that needs a person. `default=` on the mapping is not
    enough: SQLAlchemy applies that at INSERT and the database has never heard
    of it, which is exactly the trap `scope` would have fallen into.
    """
    from sqlalchemy import Column, Integer, MetaData, String, Table
    from sqlalchemy.dialects import sqlite

    from alma.db.migrate import _add_column_sql

    class _Connection:
        dialect = sqlite.dialect()

    table = Table(
        "example",
        MetaData(),
        Column("nullable_one", String(8)),
        Column("defaulted", Integer, nullable=False, server_default="0"),
        Column("python_default_only", String(8), nullable=False, default="x"),
    )
    connection = _Connection()

    assert _add_column_sql(connection, table, table.c.nullable_one).endswith("VARCHAR(8)")
    assert _add_column_sql(connection, table, table.c.defaulted).endswith("DEFAULT 0")
    with pytest.raises(SchemaTooOld, match="python_default_only"):
        _add_column_sql(connection, table, table.c.python_default_only)


def test_a_column_no_model_declares_is_named_and_its_rows_are_left_alone(
    old_database, caplog
):
    """The half of a rename this module cannot see, and must not act on.

    A renamed column reaches here as two facts that look identical to a fresh
    column and an old one: the new name is added empty, the old name keeps every
    row. Dropping the old one would be the module doing exactly what its
    docstring forbids, and staying silent about it was the real gap — the boot
    log said the migration succeeded, and it had done half the work.

    Both halves are asserted, and the data one is the one that matters: the
    value has to still be there afterwards.
    """
    import logging

    async def work():
        async with old_database.engine().begin() as connection:
            await connection.execute(
                text("ALTER TABLE purchase ADD COLUMN buyer_note VARCHAR(64)")
            )
            await connection.execute(
                text("UPDATE purchase SET buyer_note = 'do not lose me'")
            )
        await old_database.create_all()
        async with old_database.session_factory()() as session:
            kept = await session.execute(text("SELECT buyer_note FROM purchase"))
            return kept.scalar_one()

    with caplog.at_level(logging.WARNING, logger="alma.db.migrate"):
        assert run_async(work) == "do not lose me"

    assert any(
        "purchase.buyer_note" in record.getMessage() for record in caplog.records
    ), "a column the models do not know about has to be named at boot, once"


