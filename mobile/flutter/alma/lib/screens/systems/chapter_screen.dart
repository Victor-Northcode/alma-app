/// Проза главы — одна на закрытую и на открытую половину экрана.
///
/// **Один стиль, потому что это один текст.** Первый абзац приходит с сервера
/// до покупки и остаётся первым абзацем после неё; набранный до и после разными
/// гарнитурами, он доказывал бы обратное тому, ради чего паттерн построен —
/// что закрытая глава это **та же глава, дописанная наполовину**, а не другой
/// экран. По той же причине им набран и филлер под размытием: ритм строк должен
/// совпадать с настоящим, иначе размытая колонка читается чужой вставкой.
///
/// Lora 400 16/1.62 — числа эталона (`Alma - Locked Chapter Pattern.dc.html`,
/// C1–C6) и они же правило `today-reading-spec §1`: всё, что длиннее абзаца,
/// набирается гарнитурой чтения, а не интерфейсной. Здесь стоял
/// `AlmaType.body` — Golos 15.5, — и это был единственный кусок длинной прозы
/// продукта, набранный гротеском.
TextStyle _chapterProse() => AlmaType.readingBody(16)
    .copyWith(height: 1.62, color: AlmaPalette.ink);

/// Одна глава, на единственной светлой поверхности продукта.
///
/// Порт `mobile/ios/Alma/Screens/Systems/ChapterScreen.swift`. Пергамент
/// заслужен буквально: лист появляется тогда же, когда глава. Пока Alma пишет,
/// экран остаётся ночью — читать нечего, значит и документа нет.
///
/// **Жест перелистывания — два порога, как на iOS и Android.** На 56 логических
/// точках дотягивания звучит тик и появляется имя следующей главы, на 130
/// страница переворачивается. Подтверждение — расстояние, а не таймер: таймер
/// на живом устройстве вставал ровно на грань схлопывания резинки и срабатывал
/// четыре раза из пяти, а жест, которому нельзя доверять, хуже неработающего.
///
/// Физика прокрутки принудительно упругая ([BouncingScrollPhysics]): дотяжка за
/// конец существует только у неё, и на iOS пороги мерились против такой же
/// задемпфированной резинки. Android-порт в своё время сравнивал те же метки с
/// сырой протяжкой — и то же движение руки листало там и не листало на iOS.
class ChapterScreen extends StatefulWidget {
  const ChapterScreen({
    super.key,
    required this.system,
    required this.chapter,
    this.partner,
  });

  final SystemSlug system;
  final String chapter;

  /// Кого сравнивать — для глав совместимости.
  ///
  /// **Экран обязан уметь это сказать, иначе он ломается на втором человеке.**
  /// Сервер подставляет партнёра сам, но только пока сохранённый человек ровно
  /// один; при двух и более он отвечает 422 `partner_required` — и тот, у кого
  /// людей уже двое, читал «добавь человека». `null` значит «не сказано», и
  /// тогда берётся тот же человек, против которого экран системы посчитал
  /// колесо ([_partnerId]): текст главы и рисунок над оглавлением обязаны быть
  /// про одну и ту же пару.
  final Profile? partner;

  @override
  State<ChapterScreen> createState() => _ChapterScreenState();
}

class _ChapterScreenState extends State<ChapterScreen> {
  static const _nearMark = 56.0;
  static const _commitMark = 130.0;

  /// Зерно неба главы — «CHAP», буква в букву как в `ChapterScreen.swift`.
  ///
  /// **Одно на все сорок одну главу, а не своё у каждой.** Зерно у [NightSky]
  /// различает *экраны*, чтобы переход между ними был видимым переходом; глава
  /// — один экран, и перелистывание внутри него меняет текст, а не место, где
  /// его читают. Небо, пересобранное на каждой протяжке, читалось бы как
  /// подмена экрана посреди жеста, а не как следующая страница.
  static const _skySeed = 0x43484150;

  /// Какая глава показывается. Начинается с запрошенной; протяжка за конец
  /// заменяет её на следующую — **своим состоянием, не навигацией**: на iOS
  /// переход через стек навигации молча съедал анимацию, потому что стек сам
  /// владеет показом, и `transition` не спрашивался.
  late String _showing = widget.chapter;

  Reading? _reading;

  /// Права на эту главу нет — на экране паттерн закрытой главы, и запроса не
  /// будет.
  ///
  /// **Здесь стоял `_preview`, и это дважды переигранное правило.** Сначала
  /// платная глава приезжала *написанной*: сервер сочинял её целиком, помечал
  /// ответ `preview`, экран показывал первый абзац и размывал остальные.
  /// Владелец снял это — «мы не должны сразу писать всю главу, пока у человека
  /// нет подписки или купленного», — потому что за каждый такой показ платили
  /// мы, до всякого решения о покупке; на месте пробы встала чёрная стена
  /// «Unlock to read».
  ///
  /// Стена не прожила и той причины, ради которой ставилась: она ничего не
  /// показывала и ничего не доказывала, и просила заплатить за заголовок.
  /// Теперь работают обе половины сразу — **один написанный абзац** приезжает
  /// с оглавлением (`ChapterEntry.opening`, ≈40 слов, единственные токены до
  /// покупки), а хвост под ним размыт **клиентским филлером**, который не стоит
  /// ничего (`docs/monetization/locked-chapter-spec.md` §3). Экран не врёт, что
  /// глава написана, и не просит платить за пустоту.
  ///
  /// Считается **до** запроса, из оглавления (`ChapterEntry.open`) — того
  /// самого, которое только что показал экран системы, — поэтому кнопка стоит
  /// на первом кадре, а не после ответа сервера.
  bool _locked = false;

  /// Право есть, текста ещё нет: сервер сейчас пишет главу.
  ///
  /// Отдельно от `_loading`, потому что ожиданий два и они разной длины.
  /// Оглавление — обычный GET на десятки миллисекунд, письмо — сорок-девяносто
  /// секунд. «Пишу эту главу…» с рисунком принадлежит второму; показывать его
  /// на первом значило обещать текст ещё до того, как выяснилось, положен ли
  /// он вообще.
  bool _writing = false;
  ChapterList? _list;
  AlmaError? _failure;
  bool _loading = true;

  /// Открывающий абзац закрытой главы — тот единственный текст, за который мы
  /// платим до покупки. Приезжает полем `opening`; `null` — его нет, и паттерн
  /// рисуется без него.
  Reading? _opening;

  /// Солнечные знаки двоих — только для медальонов запертой главы пары (C6).
  ///
  /// В расчёте совместимости знаков двоих нет; берутся из двух натальных
  /// расчётов, как на экране системы, — сервер оба кэширует. Не доехали —
  /// медальоны не рисуются вовсе: честный недострой вместо выдуманного знака.
  String? _mySign, _theirSign;

  /// Пару нечем назвать: сервер сказал `needs_partner`. Цены на этом экране
  /// быть не должно — сначала человек, потом деньги.
  bool _needsPartner = false;

  /// Чем эта система открывается — **словом каталога сервера**, а не выводом
  /// клиента из слага.
  ///
  /// Таблица «система → товар» живёт в `catalogue.unlocks`, и вторая её копия
  /// однажды предложит «$4.99 навсегда» за транзиты. `null` — ответ ещё не
  /// приехал, и до тех пор кнопка торгует тем, что вывела сама
  /// ([chapterSku]): цена обязана стоять на первом кадре, а не после сети.
  LadderKey? _product;

  /// Сколько уже протянули за конец главы — для полоски под хвостом.
  ///
  /// **Признаком, а не полем состояния, и это была настоящая поломка.** Здесь
  /// стояло `double`, и `_onOverscroll` двигал его через `setState` — на
  /// **каждом** кадре прокрутки, а не только на дотяжке за дно. То есть вся
  /// глава — список абзацев, вклейка, мета-строка, знак конца — перестраивалась
  /// шестьдесят раз в секунду ради полоски 64×2 внизу.
  ///
  /// Владелец увидел это не там, где причина: «в главах этот ползунок двигается
  /// не плавно за движениями пальца». Нить справа ([_read]) считалась и
  /// рисовалась правильно с первого дня — у неё просто не оставалось кадров,
  /// потому что их съедала перестройка страницы рядом.
  ///
  /// Довод против `setState` каждый кадр записан прямо ниже, у `_read`, и был
  /// применён к нити, но не к протяжке. Теперь применён к обеим.
  final ValueNotifier<double> _pull = ValueNotifier(0);

  /// Сколько главы прочитано — для нити у правого поля ([GiltThread]).
  ///
  /// **Отдельным сигналом, а не полем состояния.** Прокрутка сообщает о себе
  /// каждый кадр; `setState` на каждый кадр перестраивал бы всю страницу
  /// вместе со списком абзацев — то есть платил бы разбором текста за
  /// двухточечную полоску. Слушает её один узел.
  final ValueNotifier<double> _read = ValueNotifier(0);

  /// Решётка порогов протяжки — чистая механика, юнит-тесты у неё свои
  /// (`pull_latch.dart`); экран оставляет себе только вид и хаптику.
  final PullLatch _latch = PullLatch(nearMark: _nearMark, commitMark: _commitMark);
  bool _advancing = false;

  bool _started = false;

  /// Конец главы уже засчитан — порог [_readDone] пересекается один раз за
  /// показ. Не поле «дочитано ли», а защёлка: у дна резинка ходит через порог
  /// туда-обратно каждым подрагиванием пальца, и без защёлки событие воронки
  /// умножалось бы на каждое из них.
  bool _endNoted = false;

  /// Оффер V1 в хвосте бесплатной главы. Появляется по факту дочитывания —
  /// продолжением текста, а не поверх него (ТЗ §3 P1).
  bool _endOffer = false;

  /// Приглашение «Что дальше» (V3) в хвосте последней главы купленной
  /// системы. Тоже продолжением страницы: автоперехода на экран апсейла после
  /// только что дочитанного разбора быть не должно.
  bool _whatNextInvite = false;

  // См. SystemScreen: SessionScope в initState недоступен.
  @override
  void dispose() {
    // Признак снимается вместе с экраном: бар возвращается к ночному, даже
    // если ушли жестом назад, а не кнопкой.
    readingNow.value = false;
    _read.dispose();
    _pull.dispose();
    super.dispose();
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    if (!_started) {
      _started = true;
      // **Право спрашивается до первого кадра, а не после первого ответа.**
      //
      // В главу заходят с экрана системы, который только что показал
      // оглавление; клиент помнит его (`AlmaClient.knownChapters`), и этого
      // достаточно, чтобы нарисовать стену сразу — так же, как эталон рисует
      // её на s26: заголовок, объяснение, одна кнопка. Раньше здесь начинался
      // запрос, экран показывал «Пишу эту главу…», и дверь появлялась только
      // после ответа сервера.
      final session = SessionScope.of(context);
      final known =
          session.client.knownChapters(widget.system, locale: session.locale);
      // Заодно шапка «4 / 16» встаёт правильной с первого кадра.
      if (known != null) _list = known;
      final right = _right(session);
      _locked = right == false;
      // Право известно и оно есть — значит, ждать действительно текста, и
      // «Пишу эту главу…» встаёт сразу, как вставало всегда. Пока право
      // неизвестно (оглавления не привозили), экран молчит: показывать
      // ожидание текста тому, кому текст, возможно, не положен, — то же
      // обещание, ради снятия которого всё это и делалось.
      _writing = right == true;
      _load();
    }
  }

  /// Открыта ли показываемая глава. `null` — пока неизвестно.
  ///
  /// **Права аккаунта спрашиваются первыми, и только на «да».** Открытая
  /// система открыта во всех своих главах — сервер собирает `unlocked` именно
  /// так и купленную в одиночку главу туда не кладёт, — а права обновляются
  /// покупкой сразу, тогда как оглавление в памяти могло быть привезено до
  /// неё. Порядок «сначала список» показывал бы стену тому, кто только что
  /// заплатил, и это худшая из возможных ошибок здесь.
  ///
  /// Обратное неверно: «система не куплена» ещё не значит «эта глава закрыта»
  /// — бесплатная глава платной системы открыта, — поэтому отрицательный ответ
  /// даёт только оглавление. В нём `open` считается тем же
  /// `entitlements.check`, что и стена в `POST /v1/readings`.
  bool? _right(AlmaSession session, {ChapterList? from}) {
    if (session.entitlements.opened(widget.system)) return true;
    final list = from ?? _list;
    if (list != null) {
      for (final entry in list.chapters) {
        if (entry.slug == _showing) return entry.open;
      }
    }
    return null;
  }

  /// [relist] — перечитать оглавление с сервера, а не верить памяти. Нужно
  /// после возврата с витрины: покупка меняет право, и старый список сказал бы
  /// «закрыто» тому, кто только что заплатил.
  Future<void> _load({bool relist = false}) async {
    final session = SessionScope.of(context);
    // Нить возвращается в начало вместе со страницей: следующая глава
    // прочитана на ноль, чем бы ни кончилась предыдущая.
    _read.value = 0;
    _pull.value = 0;
    setState(() {
      _loading = true;
      _failure = null;
      // Всё, что приезжало про предыдущую главу, уходит вместе с ней: абзац
      // одной главы над титулом другой — худшая из возможных ошибок здесь.
      _opening = null;
      _needsPartner = false;
      _product = null;
      // Конец главы — свойство показанной страницы, и следующая страница
      // начинается недочитанной. Сюда же попадает возврат с покупки: оффер,
      // оставшийся в хвосте у того, кто только что заплатил, читался бы как
      // «не прошло».
      _endNoted = false;
      _endOffer = false;
      _whatNextInvite = false;
    });
    try {
      // **Оглавление показывается, как только пришло, а не вместе с текстом.**
      //
      // Список глав — обычный GET и отвечает мгновенно; глава пишется 40–90
      // секунд. Пока оба ждали одного `setState`, `_entry` оставался пустым всю
      // эту минуту, и счётчик печатал запасную единицу: открытая седьмая глава
      // весь показ «Пишу эту главу…» держала в шапке «1 / 16». Снято на
      // симуляторе 13 августа 2026.
      final list = (relist || _list == null)
          ? await session.client.chapters(widget.system, locale: session.locale)
          : _list!;
      if (!mounted) return;
      setState(() {
        _list = list;
        _locked = _right(session, from: list) == false;
      });
      // Знаки двоих для медальонов C6 — параллельно и не блокируя ничего:
      // страница целиком живёт и без них.
      if (widget.system == SystemSlug.compatibility &&
          _locked &&
          _mySign == null) {
        unawaited(_loadSigns(session));
      }
      // **Закрытая глава спрашивает сервер снова — но не главу, а её первый
      // абзац.**
      //
      // Долгое время не спрашивала вовсе: право читалось из оглавления, а
      // просить текст, который решено не писать, значило ждать впустую на
      // глазах у того, кому нужна кнопка. Стена, которую эта экономия
      // оставляла, не доказывала ничего — и теперь сервер отвечает на закрытую
      // главу 200 с `locked: true` и `opening`: сорок слов средней моделью, с
      // настоящими позициями (`readings.py`, `_locked_chapter`).
      //
      // Ждать их не страшно: паттерн уже на экране — титул, размытый хвост и
      // кнопка с ценой стоят с первого кадра, потому что право известно из
      // оглавления. Абзац просто дописывается сверху, когда приедет. Поэтому
      // «Пишу эту главу…» тут не поднимается: обещать целую главу тому, кому
      // она не положена, — то же обещание, ради снятия которого всё делалось.
      if (!_locked) setState(() => _writing = true);
      final response = await session.client.reading(
        system: widget.system,
        chapter: _showing,
        locale: session.locale,
        partnerProfileId: _partnerId(session),
      );
      if (!mounted) return;
      if (response.locked) {
        // Слово сервера сильнее памяти клиента: право могло истечь между
        // оглавлением и запросом, и тогда паттерн встаёт здесь, а не по
        // догадке.
        setState(() {
          _locked = true;
          _opening = response.opening;
          _needsPartner = response.needsPartner;
          _product = LadderKey.from(response.product);
          _advancing = false;
        });
        return;
      }
      // Пергамент появляется вместе с текстом — и бар вместе с ним. Но
      // только если эта глава ещё наверху: пока она писалась, человек мог
      // уйти назад или открыть другую, и поднимать пергамент из-под чужой
      // страницы нельзя.
      final route = ModalRoute.of(context);
      if (route == null || route.isCurrent) readingNow.value = true;
      setState(() {
        _reading = response.reading;
        _advancing = false;
      });
      // Глава прочитана — счётчик системы на единицу больше. Считается
      // здесь, а не при открытии экрана: закрытая страница и ожидание письма —
      // это не чтение, а спасение от отмены (V9) обязано предлагать ту систему,
      // которую действительно читают.
      if (response.reading != null) ReadingTally.noteOpen(widget.system);
    } on AlmaError catch (error) {
      if (mounted) setState(() => _failure = error);
    } finally {
      if (mounted) {
        setState(() {
          _loading = false;
          _writing = false;
        });
      }
    }
  }

  /// Кого сравнивать в этой главе — и только для совместимости.
  ///
  /// **Первый сохранённый, а не «сервер разберётся».** Разберётся он ровно до
  /// второго человека: `_partner` в `readings.py` подставляет партнёра только
  /// при `len(others) == 1`, иначе 422. При этом экран системы считает колесо
  /// против `session.people.firstOrNull` — здесь то же правило слово в слово,
  /// потому что глава и рисунок над её оглавлением обязаны быть про одну пару.
  ///
  /// Пусто, когда людей нет вовсе: тогда 422 приходит по делу, и экран рисует
  /// дверь «добавить человека», а не молчит.
  String? _partnerId(AlmaSession session) {
    if (widget.system != SystemSlug.compatibility) return null;
    return (widget.partner ?? session.people.firstOrNull)?.id;
  }

  /// Право могло измениться — перечитываем оглавление у сервера и, если глава
  /// открылась, тем же путём идём за текстом: покупка это и есть то, после чего
  /// глава пишется целиком.
  ///
  /// Зовётся из паттерна закрытой главы, когда магазин сказал «право выдано».
  /// Отдельного «вернулись с витрины» больше нет: витрины на этом пути нет.
  Future<void> _afterOffer() async {
    if (mounted) await _load(relist: true);
  }

  /// Отказы, которые лечатся подпиской, а не дверью.
  ///
  /// Потолок бесплатного письма: право на главу есть, а денег на её написание
  /// в этом месяце уже нет. Раньше на это отвечал отдельный экран — «Alma
  /// сегодня много для тебя написала · Посмотреть планы», — и §5 спеки его
  /// удаляет: у статичной главы нет никакого «завтра», а экран смешивал разовое
  /// чтение с подпиской. Отвечает тот же паттерн закрытой главы, только продаёт
  /// он подписку (C4), потому что снимает потолок именно она.
  static const _capReasons = ['month_budget', 'budget_exceeded'];

  /// Рисуется ли сейчас паттерн закрытой главы, а не текст.
  ///
  /// **Три входа в одно состояние, и это не небрежность.** Право отсутствует по
  /// оглавлению ([_locked]) — обычный случай, известный до первого кадра; право
  /// истекло между списком и запросом (402 `locked`); письмо упёрлось в потолок
  /// месяца. Показать во всех трёх надо одно и то же: половину главы и одну
  /// кнопку. Разные экраны на них — это ровно те два экрана, которые §5 велит
  /// удалить.
  ///
  /// Подписчику потолок не продаётся: ему уже нечего купить, и вместо кнопки он
  /// получает фразу сервера — «следующее откроется завтра».
  bool _lockedPattern(AlmaSession session) {
    if (_reading != null) return false;
    // Пару нечем назвать: закрыто, но не деньгами. Цена здесь была бы вопросом
    // «с кем сравнить» по цене $4.99 — спека §1 требует сначала человека.
    if (_needsPartner) return false;
    if (_locked) return true;
    final failure = _failure;
    if (failure is! ServerRefused) return false;
    if (failure.code == 'locked') return true;
    return _capReasons.contains(failure.code) && !session.isSubscriber;
  }

  /// Метка в правом углу шапки, если ей есть что сказать.
  ///
  /// Две, и они не встречаются: «обновляется каждый день» — у живых систем
  /// (C4), «бесплатно» — у единственной свободной главы продукта (C1).
  Widget? _headBadge(L l, {required bool locked}) {
    if ((_product ?? chapterSku(widget.system)) == LadderKey.subMonthly) {
      return _ChapterBadge(l.chapterDailyBadge);
    }
    if (!locked && _entry?.free == true) {
      return _ChapterBadge(l.chapterFreeBadge);
    }
    return null;
  }

  /// Два натальных расчёта ради двух солнечных знаков — как на экране
  /// системы: сервер кэширует оба, и пара запросов стоит меньше, чем пустое
  /// место там, где холст рисует медальоны.
  Future<void> _loadSigns(AlmaSession session) async {
    final partnerId = _partnerId(session);
    if (partnerId == null) return;
    try {
      final both = await Future.wait([
        session.client.compute(SystemSlug.natal),
        session.client.compute(SystemSlug.natal, body: {'profile_id': partnerId}),
      ]);
      if (!mounted) return;
      setState(() {
        _mySign = both[0].data['sun_sign'] as String?;
        _theirSign = both[1].data['sun_sign'] as String?;
      });
    } on AlmaError {
      // Молча: медальоны — украшение правды, а не её условие.
    }
  }

  /// Закрытая глава: шесть частей эталона на той же бумаге, что и написанная.
  Widget _lockedPage(L l) {
    final entry = _entry;
    final opening = _opening;
    return _LockedChapter(
      system: widget.system,
      // Товар — слово сервера, пока оно не приехало — свой вывод. Так цена
      // стоит на первом кадре и при этом не спорит с каталогом.
      sku: _product ?? chapterSku(widget.system),
      overline: '${entry?.numeral ?? ''} · ${_systemName(l)}'.toLowerCase(),
      // Титул из оглавления, а не из абзаца: он известен до сети, и заголовок,
      // подставляющийся через десять секунд, читался бы подменой страницы.
      title: entry?.title ?? opening?.title ?? '',
      opening: opening,
      onRetryOpening: () => _load(),
      systemName: _systemName(l),
      // Обещание над кнопкой считает **платные** главы: бесплатная за деньги не
      // открывается, и включать её в счёт значило бы продавать то, что уже
      // отдано. `null` — оглавление не доехало, и число не выдумывается.
      paidChapters: _list?.chapters.where((chapter) => !chapter.free).length,
      onOpened: _afterOffer,
      partnerId: _partnerId(SessionScope.of(context)),
      mySign: _mySign,
      theirSign: _theirSign,
    );
  }

  ChapterEntry? get _entry {
    final list = _list;
    if (list == null) return null;
    for (final entry in list.chapters) {
      if (entry.slug == _showing) return entry;
    }
    return null;
  }

  /// Следующая глава, когда она есть и открыта.
  ChapterEntry? get _next {
    final list = _list;
    final current = _entry;
    if (list == null || current == null) return null;
    for (final entry in list.chapters) {
      if (entry.index == current.index + 1) return entry;
    }
    return null;
  }

  /// Порог дочитанности — доля прокрутки, после которой глава считается
  /// прочитанной. Число из ТЗ §3 P1: «скролл ≥85%». Расстояние, а не таймер —
  /// по той же причине, по которой жест перелистывания меряется метками:
  /// таймеру нельзя верить, а прокрутка и есть чтение.
  static const _readDone = 0.85;

  /// Названия следующих платных глав — для чипов оффера V1. Имена уже в
  /// оглавлении, отдельных строк им не нужно (SCREENS-V3 §V1): чипы делают
  /// работу, которую не сделает цена, — показывают, что за дверью, именами.
  List<String> get _upcomingTitles {
    final list = _list;
    final current = _entry;
    if (list == null || current == null) return const [];
    return [
      for (final entry in list.chapters)
        if (entry.index > current.index && !entry.free) entry.title,
    ].take(4).toList();
  }

  /// Первое пересечение порога дочитанности. Здесь решаются обе концовки v3 —
  /// оффер в конце бесплатной главы (V1) и приглашение «Что дальше» (V3), —
  /// обе продолжением страницы, а не отдельным экраном поверх чтения.
  void _noteEndOfChapter() {
    if (_endNoted || _reading == null) return;
    final entry = _entry;
    if (entry == null) return;
    _endNoted = true;
    final session = SessionScope.of(context);
    if (entry.free) {
      // §7 ТЗ: дочитанная бесплатная глава — ступень воронки, знаменатель
      // конверсии P1. Поверхность обязательна — сервер помечает ступень
      // monetization и без неё отвечает 422 (`alma/funnel.py`,
      // `check_surface`); дочитанное бесплатное чтение — это P1.
      session.client.track(FunnelStage.freeChapterCompleted, meta: {
        'surface': 'p1',
        'system': widget.system.slug,
      });
    }
    final door = LadderKey.doorFor(widget.system);
    final hasClosedPaid =
        _list?.chapters.any((chapter) => !chapter.free && !chapter.open) ??
            false;
    if (entry.free && door != null && hasClosedPaid) {
      // V1: только у бесплатной главы и только пока платные главы закрыты.
      // Тому, у кого всё открыто — покупкой, бандлом или подпиской, —
      // продавать нечего, и блок не появляется вовсе.
      setState(() => _endOffer = true);
      // «Пейволл показан» — один раз, в момент появления блока. Поверхность —
      // та же, что у всей двери натала ([PaywallIntent.door]): считать её по
      // месту значило бы развести один товар на две когорты; повод различает
      // `trigger`.
      session.client.track(FunnelStage.paywallShown, meta: {
        'surface': PaywallIntent.door(widget.system).surfaceCode,
        'sku': door.slug,
        'trigger': 'chapter_end',
      });
    } else if (_next == null && !entry.free && !session.isSubscriber) {
      // V3: дочитана последняя глава купленной системы — глава не заперта
      // (мы её читаем) и не единственная бесплатная. Подписчику приглашение
      // не показывается: коммерческие карточки у него исчезают целиком
      // (§4 ТЗ), и от экрана «Что дальше» не осталось бы ничего.
      setState(() => _whatNextInvite = true);
    }
  }

  /// Открыть экран «Что дальше» — по тапу на приглашение, не автопереходом.
  void _openWhatNext() {
    Navigator.of(context, rootNavigator: true).push(
      CupertinoPageRoute(
        builder: (context) => WhatNextScreen(finished: widget.system),
      ),
    );
  }

  /// [byHand] — палец на стекле, а не инерция.
  ///
  /// **Различие, которое ловит тест, и тот же баг, что жил на телефоне.**
  /// Баллистика упругой прокрутки залетает за край глубже 130 точек, и резкий
  /// смах переворачивал страницу — «слишком легко перелистывается» слово в
  /// слово. На iOS это давил сам UIScrollView: его инерционный залёт мал, и
  /// порога хватало. Во Flutter у уведомления прокрутки есть `dragDetails` —
  /// прямой ответ, рука это или инерция, — поэтому подтверждение здесь
  /// буквально то, чем оно всегда было по замыслу: рука, дотянувшая до метки.
  /// Инерция рисует полосу, но не переворачивает.
  void _onOverscroll(double distance, {required bool byHand}) {
    if (_advancing || _next == null || _loading) return;
    // Обычное чтение не трогает вообще ничего: пока за дно не тянут, тут нечему
    // меняться, и лишнее уведомление слушателю — это лишний кадр.
    if (distance == 0 && _pull.value == 0) return;
    _pull.value = distance;
    // **Палец ушёл — вот тогда и переворачиваем** (правило записано в решётке
    // вместе с порогами и гистерезисом); экрану остаются вид и хаптика.
    switch (_latch.onScroll(distance, byHand: byHand)) {
      case PullEvent.armed:
        HapticFeedback.selectionClick();
      case PullEvent.disarmed:
        // Вид взвода живёт у полосы хвоста, и она слушает `_pull` сама;
        // экрану здесь перестраивать нечего.
        break;
      case PullEvent.committed:
        // Тик тяжелее первого, чтобы рука почувствовала упор.
        HapticFeedback.mediumImpact();
      case PullEvent.advance:
        _advance();
      case PullEvent.none:
        break;
    }
  }

  void _advance() {
    final next = _next;
    if (next == null) return;
    _pull.value = 0;
    _latch.reset();
    setState(() {
      _advancing = true;
      _showing = next.slug;
      _reading = null;
    });
    HapticFeedback.heavyImpact();
    _load();
  }

  @override
  Widget build(BuildContext context) {
    // Возврат на вкладку не проходит через загрузку, поэтому признак
    // восстанавливается здесь: пергамент на экране — бар пергаментный.
    //
    // **Но только у той главы, которая сейчас наверху.** Открыв вторую главу,
    // первая остаётся смонтированной под ней в стеке маршрутов и продолжает
    // перестраиваться — и её `build` снова поднимал признак, хотя на экране
    // уже другая страница, ещё пишущаяся и потому ночная. Побеждал тот, кто
    // написал последним, и бар вставал пергаментным поверх ночи: снято на
    // устройстве, экран «глава пишется, 1 / 3».
    final route = ModalRoute.of(context);
    final onTop = route == null || route.isCurrent;
    // **Закрытая глава лежит на той же бумаге, что открытая, — в этом весь
    // паттерн.** Раньше пергамент означал «текст куплен»: без права экран
    // оставался ночью со стеной посередине, и покупка выглядела переходом на
    // другой экран. Теперь это одна страница в двух состояниях — половина
    // написана, половина размыта, — и поверхность у неё обязана быть одна.
    final locked = _lockedPattern(SessionScope.of(context));
    final onParchment = _reading != null || locked;
    if (onTop && readingNow.value != onParchment) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (mounted) readingNow.value = onParchment;
      });
    }
    final l = L.of(context);
    final total = _list?.total ?? widget.system.chapterCount;
    // Индекс сервера уже с единицы: на первой главе натива стоит «1 / 16».
    // Прибавление единицы здесь печатало «2 / 16» на главе I — найдено
    // сравнением с нативным экраном.
    final index = _entry?.index ?? 1;
    // Читается до `SafeArea`: внутри неё вырез уже съеден, и остатка не
    // вычислить.
