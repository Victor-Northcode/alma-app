                  // Потолком, а не долей. Доля была первой попыткой и дала
                  // обратный перекос: короткий абзац всё равно занимал свою
                  // пятую восьмую, между ним и оффером зиял пустой кремовый
                  // провал, а размытие сжималось в полоску под кнопкой.
                  // Потолок абзац не растягивает — он берёт свою высоту по
                  // тексту, а всё остальное достаётся размытию, как и задумано.
                  // Доля экрана, а не пункты: на маленьком телефоне оффер выше,
                  // и число, безопасное на большом, там столкнётся.
                  //
                  // Не влезшее **гасится**, а не срезается: обрыв на середине
                  // буквы читается поломкой, а гаснущая строка — тем же, чем
                  // размытие под ней, то есть продолжением, которое покупают.
                  Builder(
                    builder: (context) {
                      final cap =
                          MediaQuery.sizeOf(context).height * _openingShare;
                      return ConstrainedBox(
                        constraints: BoxConstraints(maxHeight: cap),
                        child: ShaderMask(
                          // **Гасим по факту, а не по расчёту.**
                          //
                          // Две попытки предсказать высоту текста были неверны.
                          // Первая гасила всегда — уместившийся абзац терял
                          // последнюю строку в дымку там, где текст кончился
                          // сам. Вторая мерила [TextPainter] и промахивалась
                          // ровно на строку, отчего колонка переполнялась и
                          // поверх главы ложилась жёлтая лента; обрезка её не
                          // снимает — ленту рисует сама колонка внутри своей же
                          // коробки.
                          //
                          // Здесь предсказания нет вообще. Прокрутка без
                          // прокрутки берёт высоту по тексту, а сверху её жмёт
                          // потолок, и в `rect` приходит **уже случившийся**
                          // размер: дорос до потолка — значит обрезано, значит
                          // гасим. Не дорос — градиент вырождается, абзац
                          // чёрный до последней точки.
                          shaderCallback: (rect) {
                            final cut = rect.height >= cap - 0.5;
                            return LinearGradient(
                              begin: Alignment.topCenter,
                              end: Alignment.bottomCenter,
                              colors: const [
                                Color(0xFF000000),
                                Color(0xFF000000),
                                Color(0x00000000),
                              ],
                              stops: [
                                0,
                                cut
                                    ? (1 - 28 / rect.height).clamp(0.0, 1.0)
                                    : 1,
                                1,
                              ],
                            ).createShader(rect);
                          },
                          blendMode: BlendMode.dstIn,
                          child: SingleChildScrollView(
                            physics: const NeverScrollableScrollPhysics(),
                            child: Column(
                              mainAxisSize: MainAxisSize.min,
                              crossAxisAlignment: CrossAxisAlignment.stretch,
                              children: [
                                // 18 от линейки до первой строки — то же число,
                                // что на написанной половине (4 + 14): абзац
                                // обязан стоять на той же высоте до и после
                                // покупки. Между абзацами — 14, как там же.
                                for (var i = 0; i < opening.body.length; i++)
                                  Padding(
                                    padding:
                                        EdgeInsets.only(top: i == 0 ? 18 : 14),
                                    child: Text(opening.body[i],
                                        style: _chapterProse()),
                                  ),
                              ],
                            ),
                          ),
                        ),
                      );
                    },
                  )
                else
                  // **Начала нет — и это надо сказать, а не показать пустоту.**
                  //
                  // Проверка всех сорока одной главы дала один отказ:
                  // `transits/long`, где модель трижды сослалась на то, чего в
                  // карте нет, и валидатор отказался публиковать ложную ссылку.
                  // Отказ правильный. Неправильным был экран: размытие, над
                  // которым пусто, — ровно то, что владелец назвал ошибкой
                  // словами «кусочек текста главы и заблюренная часть».
                  //
                  // Отказ оказался **случайным**: следующий же запрос написал
                  // абзац. Поэтому здесь не оправдание, а предложение повторить
                  // — тем же тоном, каким экран говорит о молчащем магазине.
                  // Выдумывать текст вместо начала нельзя ни при каких
                  // обстоятельствах: страница продаёт тем, что показывает
                  // настоящее.
                  Padding(
                    padding: const EdgeInsets.only(top: 18),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(l.stateUnavailable,
                            style: _chapterProse()
                                .copyWith(color: AlmaPalette.inkMuted)),
                        const SizedBox(height: 12),
                        AlmaButton(
                          kind: AlmaButtonKind.veil,
                          fills: false,
                          label: l.stateRetry,
                          onTap: widget.onRetryOpening,
                        ),
                      ],
                    ),
                  ),
                Expanded(
                  child: _BlurredTail(
                      gap: widget.opening?.body.isEmpty ?? true ? 18 : 14),
                ),
              ],
            ),
          ),
          Positioned(
            left: 0,
            right: 0,
            // Отсчёт от бара вкладок, а не от кромки стекла: эталон бара не
            // рисует, а устройство его имеет, и кнопка на 104 от стекла легла
            // бы под полосу. Формула — та же, что у нижнего поля написанной
            // страницы, вместе с её уроком: отступ берётся от **окна**, потому
            // что `Scaffold` с `extendBody` уже положил высоту бара в
            // `MediaQuery` тела, и сложение с ней считает бар дважды.
            bottom: AlmaMetrics.tabBarHeight +
                MediaQueryData.fromView(View.of(context)).padding.bottom +
                22,
