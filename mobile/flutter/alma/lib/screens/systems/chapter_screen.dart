                const SizedBox(height: 16),
                Container(
                    height: 1,
                    color: AlmaPalette.ink.withValues(alpha: 0.13)),
                if (widget.opening case final opening?)
                  // **Абзац обязан кончиться выше оффера, и это не отступ, а
                  // ограничение.**
                  //
                  // Он выкладывался сверху вниз без всякого предела, а оффер
