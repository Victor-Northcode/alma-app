            // подбирались под ночь и на пергаменте почти не отличаются от
            // фона. Плохую новость набираем чернилами — её надо прочитать.
            style: AlmaType.meta.copyWith(
              color: notice.tone == StoreTone.bad
                  ? AlmaPalette.ink
                  : AlmaPalette.goldDeep,
            ),
          ),
        ],
      ],
    );
  }
