/// Марки Apple и Google на кнопках входа.
///
/// **Чужие знаки рисуются точно или не рисуются вовсе.** Обе компании требуют
/// использовать свой знак ровно таким, каким они его выпустили: у Google это
/// четырёхцветная «G» с зафиксированными дугами и углами, у Apple — яблоко из
/// её собственного шрифта. Похожий знак, нарисованный на глаз, — не экономия, а
/// нарушение обоих гайдлайнов сразу, и заметно оно первому же дизайнеру.
///
/// Поэтому здесь нет ни одной подобранной кривой: «G» — официальный контур в
/// четыре пути, яблоко — глиф системного шрифта Apple.
class BrandMark {
  const BrandMark._();

  /// Знак Apple, размером с прописную букву рядом.
  ///
  /// **Это глиф, а не картинка, и так и должно быть.** U+F8FF в шрифтах Apple —
  /// её собственное яблоко; на iOS оно приходит вместе с системой, всегда
  /// правильной формы и всегда того веса, который просит текст. Свой контур
  /// пришлось бы тащить в бандл и обновлять за Apple.
  ///
  /// Вне платформ Apple этого глифа нет — там он выпал бы пустым квадратом. И
  /// не выпадет: кнопка Apple показывается только на iOS
  /// (`AlmaProviders.appleShows`), потому что и самого входа на Android нет.
  static Widget apple({double size = 17}) => Text(
        '',
        style: TextStyle(
          fontSize: size,
          color: AlmaPalette.inkLight,
          // Явно системным шрифтом: наш Golos этого знака не содержит, и без
          // указания текст ушёл бы в него первым.
          fontFamily: kIsWeb || !Platform.isIOS ? null : '.SF UI Text',
          fontFamilyFallback: const ['-apple-system', 'SF Pro Text', 'Apple Symbols'],
          height: 1,
        ),
      );

  /// Официальная четырёхцветная «G».
  ///
  /// Контур — тот, что Google раздаёт для кнопок входа: четыре дуги в её
  /// фирменных цветах на прозрачном фоне, viewBox 48×48. Ни один узел не
  /// подобран и не упрощён.
  static Widget google({double size = 17}) => SizedBox(
        width: size,
        height: size,
        child: SvgPicture.string(_googleG),
      );
}

