import 'package:flutter/widgets.dart';

/// Размеры, которые в продукте одинаковы везде.
///
/// Порт `mobile/ios/Alma/DesignSystem/Metrics.swift`. Числа перенесены как
/// есть — см. соображение в `palette.dart` о том, почему их нельзя «уточнять»
/// на новом месте.
class AlmaMetrics {
  const AlmaMetrics._();

  /// Боковое поле. Одно на весь продукт.
  static const pad = 22.0;

  /// Предел ширины колонки текста. Дальше строка становится длиннее, чем глаз
  /// удерживает без потери строки, и планшет начинает читаться хуже телефона.
  static const readingWidth = 620.0;

  // Бар стоял высоковато — 58 точек воздуха над домашним индикатором. 52
  // сажают его ниже, ближе к краю, и подписи перестают висеть в середине.
  static const tabBarHeight = 52.0;

  static const gap = 16.0;
  static const gapLarge = 28.0;
  static const gapSection = 44.0;

  static const buttonHeight = 56.0;
  static const buttonHeightOutline = 54.0;
  static const buttonHeightVeil = 50.0;
  static const fieldHeight = 54.0;
}

/// Словарь движения: четыре длительности и три кривые, чтобы лист и нажатие
/// никогда не расходились в том, с какой скоростью движется продукт.
///
/// «Небо движется, интерфейс — нет»: всё здесь про **элементы управления**, и
/// всё короткое. Фоновое движение неба живёт на своих, гораздо более медленных
/// часах и ничего отсюда не берёт.
///
/// **Кривые перенесены как кубические Безье, а не подобраны на глаз.**
/// `Animation.timingCurve(a, b, c, d)` в SwiftUI и `Cubic(a, b, c, d)` во
/// Flutter — это одна и та же кривая с одними и теми же контрольными точками,
/// поэтому движение совпадает не «примерно», а точно. Именно эти числа
/// подбирались руками на устройстве: 0.30 для смены страницы и 0.42 для
/// перелистывания главы — не круглые, потому что круглые ощущались хуже.
class AlmaMotion {
  const AlmaMotion._();

  /// Нажатие, подтверждающее само себя.
  static const tapCurve = Cubic(0.2, 0, 0.4, 1);
  static const tap = Duration(milliseconds: 120);

  /// Элемент, меняющий состояние.
  static const uiCurve = Cubic(0.22, 1, 0.36, 1);
  static const ui = Duration(milliseconds: 240);

  /// Приходящий лист или полноэкранная накладка.
  static const sheetCurve = Cubic(0.16, 1, 0.3, 1);
  static const sheet = Duration(milliseconds: 380);

  /// Глава, проявляющаяся после покупки. Намеренно самое медленное в
  /// приложении из того, что не является небом: это момент, когда продукт
  /// отдаёт купленное.
  static const revealCurve = Cubic(0.22, 1, 0.36, 1);
  static const reveal = Duration(milliseconds: 620);

  /// Одна страница уступает место следующей — глава, в которую втянули, или
  /// вкладка, к которой смахнули.
  ///
  /// **Быстрее листа и медленнее элемента управления — в этом всё задание.**
  /// Смена страницы длиной с лист ощущается как раздумье приложения; длиной с
  /// кнопку — как сбой.
  static const pageCurve = Cubic(0.2, 0.9, 0.25, 1);
  static const page = Duration(milliseconds: 300);

  /// Одна глава уступает следующей под протяжкой.
  ///
  /// Длиннее `page` и мягче в конце, потому что эту анимация **заканчивает**, а
  /// не начинает: половину движения палец уже сделал, и оставшееся должно
  /// выглядеть как оседающая страница, а не как приезжающий экран.
  static const turnCurve = Cubic(0.16, 1, 0.28, 1);
  static const turn = Duration(milliseconds: 420);
}
