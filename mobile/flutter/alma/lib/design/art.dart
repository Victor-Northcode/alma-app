import '../net/models.dart' show SystemSlug;

/// Единственное место, где имена картинок написаны буквами.
///
/// Строковый путь, набранный по месту, ошибается молча: Flutter не находит
/// ассет, рисует пустоту и пишет в консоль, которую на устройстве никто не
/// читает. Здесь путь собирается из перечисления, а тест проверяет, что каждому
/// имени отсюда соответствует файл на диске и запись в `pubspec.yaml`.
/// **Перегонять только из `assets/`, никогда из `assets/opt/`.**
///
/// В дизайн-пакете папка `opt` названа рабочей, и это сбивает: она собрана как
/// веб-превью для холста эталонов, а не как спека бандла. Небо там 720 точек в
/// ширину — под @3x нужно 1320, и на телефоне вышло бы мыло на каждом экране.
/// Всё, что лежит в `assets/img`, перегнано из полноразмерных оригиналов:
/// небо 1320×2358, карты 840×1260, WebP q80, три масштаба. Исключений нет.
///
/// **Золочёной бумаги здесь больше нет.** Она была здесь один день: снимок
/// листа в раме застилал главу по кадрам `s51`/`s52`, и он был единственной
/// картинкой бандла без полноразмерного оригинала — три масштаба собирались
/// растяжением из `opt/paper-gilt.jpg` шириной 804. Владелец, посмотрев экран,
/// попросил вернуть простой светлый фон, и вместе с текстурой ушла и уступка:
/// правило «гоним из оригинала» снова без единого исключения.
class AlmaArt {
  const AlmaArt._();

  static const _dir = 'assets/img';

  /// Туманность за всем продуктом. Стоит на всех сорока восьми эталонных
  /// экранах и всегда под скримом — см. `NightBackground`.
  static const sky = '$_dir/bg-sky.webp';

  /// Небо живого слоя — карточка на экране подписки (`V6`).
  ///
  /// **Владелец сказал прямо: «тут не та картинка стоит».** Экран подписки
  /// рисовал `sky` — общую туманность, которая лежит фоном под всеми сорока
  /// восемью экранами. На холсте там своя вклейка, и разница читается: фон
  /// нельзя показывать как предмет продажи, иначе карточка выглядит дырой в
  /// фоне, а не картиной.
  ///
  /// **Почему в бандле, хотя это вклейка главы.** Сервер отдаёт её среди
  /// тридцати пяти (`backend/static/plates/plate-sky.webp`), и глава берёт
  /// вклейки оттуда — они нужны после сети по определению. Пейволл нужен
  /// раньше: он встречается на первом же импульсе, и ждать картинку в момент,
  /// когда человек решает платить, значит показать ему пустую рамку в
  /// единственную секунду, ради которой экран существует. То же правило, по
  /// которому здесь лежит весь продающий слой.
  ///
  /// Ширина 360 точек от логических 358 карточки (402 минус поле 22 с двух
  /// сторон), три масштаба. Оригинал 420×630, поэтому @3x — растяжение;
  /// уступка та же, что была у золочёной бумаги, и здесь она дешевле: карточка
  /// стоит под скримом и обрезана по `object-fit: cover`.
  static const skyPlate = '$_dir/plate-sky.webp';

  /// Продающий слой. Каждая картина встречается один-два раза и только на
  /// пороге: витрина, дверь, приглашение.
  static const gates = '$_dir/art-gates.webp';
  static const fan = '$_dir/art-fan.webp';
  static const couple = '$_dir/art-couple.webp';
  static const globe = '$_dir/art-globe.webp';

  /// Филигрань-разделитель. **Сейчас её никто не ставит, и это осознанно.**
  ///
  /// **Альфы у файла нет.** Здесь стояло «кладётся маской, а не картинкой
  /// поверх фона» — и это было неправдой про этот файл: 358×120 WebP без
  /// альфа-канала, снимок броши на синем бархате. Положенный как есть, он даёт
  /// на небе прямоугольник с видимыми краями.
  ///
  /// **В эталонах его нет ни на одном экране.** 16 августа 2026 витрина
  /// (`offer_screen.dart`) держала его полосой между фактами и лестницей, с
  /// кадрированием и градиентным гашением по обеим осям, — и владелец назвал
  /// это «непонятным куском», висящим между текстом и ступенями. Сверка с
  /// дизайн-проектом его правоту подтвердила: в разметке всех экранов
  /// `art-divider` не встречается ни разу, разделитель там всегда рисованный —
  /// волос, гаснущий с обоих концов (`AlmaGradient.fadedRule`).
  ///
  /// Путь оставлен: файл лежит в бандле, и тест сверяет его с диском. Но кто
  /// решит его поставить, тот сначала находит экран эталона, на котором он
  /// стоит, а потом уже кадрирует полосой и гасит края маской.
  static const divider = '$_dir/art-divider.webp';

  /// Карта системы для колоды «Мои системы» и для героя двери.
  ///
  /// Один файл на оба места: в колоде карта рисуется вчетверо мельче своего
  /// размера, и это дешевле, чем держать два набора.
  ///
  /// **Карты с лицами временно ходят под небом.** Владелец, 29.08.2026:
  /// «поменять картинки у систем, убрать лица (я сделаю новые картинки),
  /// кроме раздела совместимости». Каждый из восьми файлов просмотрен
  /// глазами: лица — на пяти (натал, карта рождения, соляр, астрокартография,
  /// синтез); нумерология (диск с числами) и транзиты (армиллярная сфера) —
  /// предметные и остаются, как и карта пары. Первая версия правки прятала
  /// все семь — «было 6 картинок, а щас их нету». Подмена в одной точке:
  /// вычеркнуть слаг из списка, когда приедет новый файл. `sky` — туманность
  /// без единого лица; `plate-sky` не годится, на ней тоже лицо.
  static const _cardFaces = {
    SystemSlug.natal, SystemSlug.birthCard, SystemSlug.solarReturn,
    SystemSlug.astrocartography, SystemSlug.synthesis,
  };

  static String card(SystemSlug system) => _cardFaces.contains(system)
      ? sky
      : '$_dir/card-${_cardName(system)}.webp';

  /// Имена файлов художника не совпадают со слагами движка в трёх местах из
  /// восьми, и это не повод переименовывать ни то, ни другое: слаг — контракт
  /// с сервером, имя файла — контракт с дизайн-пакетом. Карта между ними живёт
  /// здесь, одна на приложение.
  static String _cardName(SystemSlug system) => switch (system) {
        SystemSlug.natal => 'natal',
        SystemSlug.numerology => 'numerology',
        SystemSlug.birthCard => 'birthcard',
        SystemSlug.transits => 'transits',
        SystemSlug.solarReturn => 'solar',
        SystemSlug.compatibility => 'compat',
        SystemSlug.astrocartography => 'astro',
        SystemSlug.synthesis => 'synthesis',
      };

  /// Всё, что вшито в приложение, — для теста, который сверяет список с диском.
  /// Файлы карт названы напрямую, а не через `card()`: подмена небом выше —
  /// про показ, а не про бандл, и файлы художника остаются на диске до замены.
  static List<String> get bundled => [
        sky, skyPlate, gates, fan, couple, globe, divider,
        for (final s in SystemSlug.values) '$_dir/card-${_cardName(s)}.webp',
      ];
}
