import 'package:shared_preferences/shared_preferences.dart';

/// Память об обучалке: пройдена ли анкета и показывали ли уже проводку.
///
/// **Тем же способом, что и вся остальная клиентская память.** `ReadingTally`,
/// счёт запусков карточки «сохрани карту» и отказ от неё живут в
/// `SharedPreferences` под ключами с точками (`alma.*`, `reading.*`), и заводить
/// ради двух булевых значений отдельный файл, базу или поле на сервере значило
/// бы завести второй способ помнить одно и то же. Здесь тот же способ и та же
/// цена: память умирает вместе с установкой — что для «показать один раз в
/// жизни установки» ровно то, что обещано.
///
/// **Признаков два, и второй не лишний.**
///
/// `seen` отвечает на «показывали ли», `armed` — на «есть ли кому показывать».
/// Без второго обучалку увидел бы каждый, кто обновил приложение с уже
/// построенной картой: у него анкеты не было, кабинет он знает наизусть, и
/// накладка поверх знакомого экрана читалась бы поломкой. Взводит признак
/// оболочка в ту секунду, когда путешествие сказало «я закончила», — то есть
/// ровно тот человек, ради которого обучалка и затевалась.
///
/// **Ничего личного здесь не лежит** — два булевых значения и ни одного факта о
/// человеке.
class OnboardingMemory {
  const OnboardingMemory._();

  /// Анкета пройдена, обучалка ждёт первого открытого кабинета.
  ///
  /// Пишется на диск, а не держится полем в памяти процесса: между концом
  /// церемонии и первым кадром кабинета приложение может быть убито (звонок,
  /// нехватка памяти), и человек, потерявший обучалку из-за чужого звонка, — не
  /// тот случай, ради которого стоит экономить один ключ.
  static const _armedKey = 'alma.onboarding.armed';

  /// Показана — и больше никогда. Ставится **до** показа, а не после закрытия:
  /// «один раз в жизни установки» обязано выполняться и для того, кто закрыл
  /// её убийством приложения, а не крестиком.
  static const _seenKey = 'alma.onboarding.seen';

  /// Путешествие закончилось: следующий открывшийся кабинет несёт обучалку.
  static Future<void> arm() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool(_armedKey, true);
  }

  /// Пора ли показывать.
  static Future<bool> due() async {
    final prefs = await SharedPreferences.getInstance();
    if (prefs.getBool(_seenKey) ?? false) return false;
    return prefs.getBool(_armedKey) ?? false;
  }

  /// Показали. Взвод снимается заодно: держать его после показа незачем, а
  /// оставленный он однажды переживёт очистку `seen` руками из отладки и
  /// приведёт обучалку туда, где её не ждут.
  static Future<void> markSeen() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool(_seenKey, true);
    await prefs.remove(_armedKey);
  }
}
