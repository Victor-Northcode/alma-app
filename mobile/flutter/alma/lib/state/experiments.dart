/// Присвоение вариантов A/B — детерминированное и без сети.
///
/// Ф3 ТЗ монетизации v3 просит механизм экспериментов: цена набора, позиция
/// карточки совместимости, наличие ссылки на набор в конце бесплатной главы.
/// Для всех трёх достаточно одного свойства: **один и тот же человек всегда
/// попадает в один и тот же вариант**, на любом устройстве входа и без
/// обращения к серверу в момент отрисовки.
///
/// Поэтому вариант — хеш от (имя эксперимента, идентификатор человека), а не
/// запись в базе. Запись пришлось бы читать до первого кадра экрана — то есть
/// либо ждать сеть, либо мигать переключением варианта на глазах; хеш отвечает
/// мгновенно и одинаково всегда.
///
/// **Экспозиция не шлётся отдельной ступенью.** Воронка сервера принимает
/// только известные ей имена (`alma/funnel.py`, закрытый список), и ступень
/// «показан вариант» в нём не заведена — вместо этого вариант едет полем meta
/// на той ступени, где эксперимент применяется (`paywall_shown` несёт
/// `experiment`/`variant`). Отчёт складывает конверсию по вариантам из тех же
/// строк, по которым считает поверхность.
library;

/// Детерминированный выбор варианта.
///
/// FNV-1a по строке «эксперимент:субъект» — не криптография и не должна ею
/// быть: требуется только устойчивость и равномерность на паре десятков тысяч
/// человек. Субъект — устойчивый идентификатор аккаунта (или установки, пока
/// аккаунта нет): смена субъекта после входа честно перекинет человека в его
/// «настоящий» вариант, и это правильнее, чем вечно держать вариант установки.
String assignVariant({
  required String experiment,
  required String subject,
  required List<String> arms,
}) {
  assert(arms.isNotEmpty, 'эксперимент без вариантов — не эксперимент');
  var hash = 0x811C9DC5;
  for (final unit in '$experiment:$subject'.codeUnits) {
    hash ^= unit;
    hash = (hash * 0x01000193) & 0xFFFFFFFF;
  }
  // Финальное перемешивание — обязательное, и найдено тестом, а не теорией.
  // Младший бит чистого FNV-1a линеен по чётности входа: умножение на нечётное
  // чётности не меняет, и `hash % 2` сводился к XOR чётностей всех байтов.
  // Два эксперимента с именами в один символ разницы («exp-a»/«exp-b»)
  // переворачивали вариант **каждому** человеку синхронно — то есть вторая
  // выборка была не независимой, а зеркальной. Лавина ниже — финализатор
  // MurmurHash3: после неё младшие биты зависят от всех входных.
  hash ^= hash >> 16;
  hash = (hash * 0x85EBCA6B) & 0xFFFFFFFF;
  hash ^= hash >> 13;
  hash = (hash * 0xC2B2AE35) & 0xFFFFFFFF;
  hash ^= hash >> 16;
  return arms[hash % arms.length];
}
