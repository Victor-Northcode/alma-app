import 'package:flutter/foundation.dart' show visibleForTesting;

import '../design/palette.dart' show readingNow;

/// Инварианты ненавязчивости §5 ТЗ — в одном месте и без единого экрана рядом.
///
/// **Живёт в `state/`, а не рядом с пейволлами, по одной причине.** Часы тишины
/// после покупки заводит магазин (`billing/alma_store.dart`), а спрашивает их
/// маршрутизатор (`screens/paywall/`); если бы правило лежало у пейволлов,
/// магазину пришлось бы импортировать экраны — то есть слой, который знает про
/// деньги, начал бы зависеть от слоя, который знает про кнопки. Состояние
/// сессии — общая земля для обоих, и оно же честно описывает, чем эта вещь
/// является: не экраном и не покупкой, а тем, что продукт помнит о себе в
/// течение сессии.

/// Почему пейволл не показан.
enum PaywallRefusal {
  /// Показывать можно.
  none,

  /// Поверх другого пейволла. §5 правило 3.
  overPaywall,

  /// Во время чтения главы. §5 правило 3: цена не встаёт поперёк текста.
  ///
  /// Оффер в конце бесплатной главы (V1, P1) этим правилом не отменяется и
  /// сюда не приходит вовсе: по спеке это **секция самой главы**, а не
  /// отдельный экран, — он появляется, когда читать больше нечего.
  whileReading,

  /// Десять минут после любой покупки. §5 правило 3.
  ///
  /// **Читается буквально, и цена этого известна.** Тот, кто через минуту
  /// после покупки ткнёт в закрытую главу другой системы, не увидит ничего —
  /// нажатие окажется пустым. Обратное прочтение («правило про всплывающие
  /// пейволлы, а тапнутый — ответ на действие») выглядит разумнее, но оно
  /// именно прочтение: в §5 написано «никогда», и смягчать чужое «никогда»
  /// молча нельзя. Вопрос владельцу назван в отчёте Ф1.
  afterPurchase,

  /// Проактивный оффер в этой сессии уже был. §5 правило 1.
  proactiveSpent,
}

/// Четыре правила §5, которые нельзя проверить на экране.
///
/// Проверять их обязан тот, кто **решает показать**, а не тот, кто рисует:
/// экран, спрошенный «можно ли тебе появиться», всегда ответит «да».
class PaywallGuard {
  const PaywallGuard._();

  /// Сколько молчит продукт после любой покупки.
  static const cooldown = Duration(minutes: 10);

  /// Открыт ли пейволл прямо сейчас. Поднимает [showPaywall] вокруг push.
  static bool onScreen = false;

  static DateTime? _boughtAt;
  static bool _proactiveSpent = false;

  /// Покупка состоялась. Зовёт `AlmaStore`, когда сервер выдал право, —
  /// **не экран**: покупка приходит и без экрана (восстановление, отложенное
  /// одобрение, покупка на другом устройстве), и тишина после неё положена
  /// в любом случае.
  static void notePurchase([DateTime? at]) => _boughtAt = at ?? DateTime.now();

  /// Проактивный показ в этой сессии уже был.
  static void noteProactive() => _proactiveSpent = true;

  static PaywallRefusal check({required bool proactive, DateTime? now}) {
    if (onScreen) return PaywallRefusal.overPaywall;
    if (readingNow.value) return PaywallRefusal.whileReading;
    final bought = _boughtAt;
    if (bought != null &&
        (now ?? DateTime.now()).difference(bought) < cooldown) {
      return PaywallRefusal.afterPurchase;
    }
    if (proactive && _proactiveSpent) return PaywallRefusal.proactiveSpent;
    return PaywallRefusal.none;
  }

  /// Сессия начинается заново — и вместе с ней счётчик проактивных офферов.
  /// Тишина после покупки сюда не входит: она принадлежит покупке, а не
  /// запуску, и переживает перезапуск ровно так же, как деньги.
  @visibleForTesting
  static void reset() {
    onScreen = false;
    _boughtAt = null;
    _proactiveSpent = false;
  }
}
