    /// The system names, ours rather than the store's.
    ///
    /// **This is deliberately not `Product.displayName`,** which would be the
    /// obvious choice and is wrong. App Store Connect localises product metadata
    /// per *storefront*, not per device language: a German speaker with a US
    /// Apple ID sees the US storefront, so `displayName` would put "Natal chart"
    /// in the middle of a German paywall. The price has to come from StoreKit
    /// because that is the money; the name has to come from here because that is
    /// the language.
    static func systemName(_ system: SystemSlug) -> LocalizedStringResource {
        switch system {
        case .natal: res("paywall.system.natal", "Natal chart")
        case .numerology: res("paywall.system.numerology", "Numerology")
