import Foundation

/// Every string the paywall shows, named — the same discipline as `L10n`, in a
/// table of its own.
///
/// **Why a second String Catalog rather than more keys in `Localizable`.** Three
/// agents are adding screens to this project at the same time, and
/// `Localizable.xcstrings` is one JSON document: two of them appending keys to it
/// is the one merge conflict a file-system synchronized folder group cannot
/// prevent. A separate table is a separate file, it compiles to its own
/// `Paywall.strings` inside each `.lproj`, and `LocalizedStringResource` resolves
/// it by name — so the isolation costs one `table:` argument and buys a file
/// nobody else writes to. If the two are ever merged, every constant below moves
/// and no call site changes.
///
/// **The wording is not invented here where it already existed.** Most of these
/// are lifted from `src/lib/i18n/`, so the app and the web say the same sentence
/// in the same voice; the comment on each catalogue entry names the key it came
/// from. Three of them were deliberately *changed* rather than copied, and that
/// is the interesting part:
///
/// * `pricing.renewsNote` promises cancelling is "two taps, from Settings". On
///   iOS it is not: Apple owns the subscription and the cancel control lives in
///   the Apple ID settings. Shipping the web sentence would be a false statement
///   about a recurring charge, on the screen where the charge is agreed to.
/// * `pricing.honesty[1]` promises an email before every renewal. That email is
///   sent by our own webhook when *we* are the merchant. Apple is the merchant
///   here and the renewal notice is Apple's.
/// * `pricing.honesty[2]` says the same thing as `renewsNote` and gets the same
///   correction.
///
/// Everything is regenerated by `tools/gen_paywall_strings.py`, which is where a
/// new key goes: the six languages sit next to each other there, and the script
/// refuses to write a key that is missing one.
